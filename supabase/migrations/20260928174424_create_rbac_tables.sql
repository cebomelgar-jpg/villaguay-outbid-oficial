/*
# RBAC: User Roles, Access Keys, Support Tickets

1. New Tables
- `user_roles`: Maps auth.users to a role (admin, moderator, merchant, promoter, client)
- `access_keys`: Invitation keys generated by admin for merchant/promoter registration
- `support_tickets`: Messages/tickets from merchants requesting profile changes

2. Security
- `user_roles`: Users read own role. Admins read/update all.
- `access_keys`: Admins CRUD. Moderators read. Anyone can verify by code.
- `support_tickets`: Users CRUD own. Staff read all + update.

3. Helper Functions
- `is_admin()`, `is_moderator()`, `is_staff()`
*/

-- ============================================================
-- user_roles
-- ============================================================
CREATE TABLE IF NOT EXISTS user_roles (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  role TEXT NOT NULL DEFAULT 'client' CHECK (role IN ('admin', 'moderator', 'merchant', 'promoter', 'client')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE user_roles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "read_own_role" ON user_roles;
CREATE POLICY "read_own_role" ON user_roles FOR SELECT
  TO authenticated USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "admin_read_all_roles" ON user_roles;
CREATE POLICY "admin_read_all_roles" ON user_roles FOR SELECT
  TO authenticated USING (
    EXISTS (SELECT 1 FROM user_roles ur WHERE ur.user_id = auth.uid() AND ur.role = 'admin')
  );

DROP POLICY IF EXISTS "admin_update_roles" ON user_roles;
CREATE POLICY "admin_update_roles" ON user_roles FOR UPDATE
  TO authenticated USING (
    EXISTS (SELECT 1 FROM user_roles ur WHERE ur.user_id = auth.uid() AND ur.role = 'admin')
  ) WITH CHECK (
    EXISTS (SELECT 1 FROM user_roles ur WHERE ur.user_id = auth.uid() AND ur.role = 'admin')
  );

DROP POLICY IF EXISTS "admin_insert_roles" ON user_roles;
CREATE POLICY "admin_insert_roles" ON user_roles FOR INSERT
  TO authenticated WITH CHECK (
    EXISTS (SELECT 1 FROM user_roles ur WHERE ur.user_id = auth.uid() AND ur.role = 'admin')
  );

DROP POLICY IF EXISTS "admin_delete_roles" ON user_roles;
CREATE POLICY "admin_delete_roles" ON user_roles FOR DELETE
  TO authenticated USING (
    EXISTS (SELECT 1 FROM user_roles ur WHERE ur.user_id = auth.uid() AND ur.role = 'admin')
  );

