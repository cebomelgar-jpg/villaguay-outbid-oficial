export function enrichVillaguayBusiness(biz: Business): Business {
  const hoursEmpty = !biz.businessHours || Object.values(biz.businessHours).every((v) => !v);
  const servicesEmpty = !biz.services || biz.services.length === 0;
  const derivedService = biz.slogan?.replace(/^Comercio en\s+/i, '').trim();
  const address = biz.address?.includes('Villaguay')
    ? biz.address
    : `${biz.address}, Villaguay, Entre Ríos`;

  return {
    ...biz,
    address,
    businessHours: hoursEmpty ? HOURS_BY_CATEGORY[biz.category] : biz.businessHours,
    services: servicesEmpty
      ? SERVICES_BY_SUBCATEGORY[biz.subcategory] || (derivedService ? [derivedService] : [])
      : biz.services,
    socialLinks: {
      whatsapp: biz.socialLinks?.whatsapp || biz.whatsapp || '',
      instagram: biz.socialLinks?.instagram || biz.instagram || '',
      googleMaps: biz.socialLinks?.googleMaps || biz.googleMaps || '',
    },
  };
}

